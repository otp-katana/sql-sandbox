USE TechStart_DB;
GO

-- 1. Yaş Aralığı Filtrelemesi
SELECT * FROM EKIP
WHERE YAS BETWEEN 25 AND 32;
GO

-- 2. Maaş Aralığı Filtrelemesi ve İsimlendirme (Alias)
SELECT AD_SOYAD AS 'CALISAN_ISMI', MAAS AS 'NET_UCRET' FROM EKIP
WHERE MAAS BETWEEN 35000 AND 45000;
GO

-- 3. Şirket Geneli Metrikler
SELECT COUNT(*) AS TOPLAM_CALISAN_SAYISI,
	SUM(MAAS) AS TOPLAM_MAAS_GIDERI,
	MIN(PERFORMANS_PUANI) AS EN_DUSUK_PERFORMANS,
	MAX(PERFORMANS_PUANI) AS EN_YUKSEK_PERFORMANS
FROM EKIP;
GO

-- 4. Departman Bazlı Çalışan Sayısı Analizi
SELECT DEPARTMAN, COUNT(*) AS CALISAN_SAYISI
FROM EKIP
GROUP BY DEPARTMAN;
GO

-- 5. İsim Analizi (Başlangıç Harfi)
SELECT * FROM EKIP
WHERE AD_SOYAD LIKE 'C%';
GO

-- 6. Soyad Analizi (Bitiş Harfi)
SELECT AD_SOYAD, DEPARTMAN FROM EKIP
WHERE AD_SOYAD LIKE '%K';
GO

-- 7. Kısmi Departman Araması (İçeren)
SELECT * FROM EKIP
WHERE DEPARTMAN LIKE '%ZIL%';
GO