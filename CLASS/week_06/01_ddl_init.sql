USE master;
GO
CREATE DATABASE EtkinlikBilet_DB;
GO
USE EtkinlikBilet_DB;
GO

-- 1. Kullanıcılar Tablosu
CREATE TABLE KULLANICILAR (
    KULLANICI_ID INT PRIMARY KEY IDENTITY(1, 1),
    AD_SOYAD VARCHAR(60),
    SEHIR VARCHAR(30),
    YAS INT
);
GO

-- 2. Etkinlikler Tablosu
CREATE TABLE ETKINLIKLER (
    ETKINLIK_ID INT PRIMARY KEY, 
    ETKINLIK_ADI VARCHAR(80),
    KATEGORI VARCHAR(30),
    SEHIR VARCHAR(30),
    TARIH DATE, 
    BILET_FIYATI DECIMAL(10,2),
    KAPASITE INT 
);
GO

-- 3. Biletler Tablosu
CREATE TABLE BILETLER (
    BILET_ID INT PRIMARY KEY IDENTITY(1,1),
    KULLANICI_ID INT,
    ETKINLIK_ID INT,
    SATIN_ALMA_TARIHI DATE,
    ODENEN_TUTAR DECIMAL(10,2),
    DURUM VARCHAR(20)
);
GO